#!/usr/bin/env python3
"""Generates unicode_tables.hh from UnicodeData.txt: general categories and simple
lowercase mappings as two-stage tables (256-code-point blocks, deduplicated).

  gen_tables.py UnicodeData.txt VERSION > unicode_tables.hh
  gen_tables.py --check UnicodeData.txt ORACLE_DUMP   compare with a "cp category lower" dump
"""
import sys

CATEGORIES = ["Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Me", "Mc", "Nd", "Nl", "No", "Zs", "Zl", "Zp",
              "Cc", "Cf", "Co", "Cs", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So"]
MAX = 0x110000


def load(path):
    category = [0] * MAX
    lower = list(range(MAX))
    first = None
    for line in open(path, encoding="utf-8"):
        f = line.rstrip("\n").split(";")
        cp, name, cat = int(f[0], 16), f[1], CATEGORIES.index(f[2])
        if name.endswith(", First>"):
            first = cp
            continue
        start = first if name.endswith(", Last>") else cp
        first = None
        for c in range(start, cp + 1):
            category[c] = cat
        if f[13]:
            lower[cp] = int(f[13], 16)
    return category, lower


def check(ucd, dump):
    category, lower = load(ucd)
    expected = {}
    for line in open(dump):
        cp, cat, low = map(int, line.split())
        expected[cp] = (cat, low)
    bad = 0
    for cp in range(MAX):
        want = expected.get(cp, (0, cp))
        got = (category[cp], lower[cp])
        if got != want:
            bad += 1
            if bad <= 10:
                print(f"U+{cp:04X}: ucd {got} oracle {want}")
    print(f"{bad} differences")
    return bad


def emit(ucd, version):
    category, lower = load(ucd)

    def two_stage(values):
        blocks, index, stage1 = [], {}, []
        for b in range(0, MAX, 256):
            block = tuple(values[b:b + 256])
            if block not in index:
                index[block] = len(blocks)
                blocks.append(block)
            stage1.append(index[block])
        return stage1, blocks

    cat1, cat2 = two_stage(category)
    delta = [lower[c] - c for c in range(MAX)]
    low1, low2 = two_stage(delta)
    out = []
    out.append("// Generated by tools/gen_tables.py from UnicodeData.txt (Unicode %s). Do not edit." % version)
    out.append("// Derived from the Unicode Character Database; see LICENSE-UNICODE.")
    out.append("#pragma once\n#include <cstdint>\nnamespace unicode::tables {")
    out.append('inline constexpr const char version[] = "%s";' % version)
    def index_type(blocks):
        return "std::uint8_t" if len(blocks) <= 256 else "std::uint16_t"

    out.append("inline constexpr %s category_stage1[%d] = {%s};" % (index_type(cat2), len(cat1), ",".join(map(str, cat1))))
    out.append("inline constexpr std::uint8_t category_stage2[%d][256] = {%s};" % (len(cat2), ",".join("{" + ",".join(map(str, b)) + "}" for b in cat2)))
    out.append("inline constexpr %s lower_stage1[%d] = {%s};" % (index_type(low2), len(low1), ",".join(map(str, low1))))
    out.append("inline constexpr std::int32_t lower_stage2[%d][256] = {%s};" % (len(low2), ",".join("{" + ",".join(map(str, b)) + "}" for b in low2)))
    out.append("}  // namespace unicode::tables")
    print("\n".join(out))


if __name__ == "__main__":
    if sys.argv[1] == "--check":
        sys.exit(1 if check(sys.argv[2], sys.argv[3]) else 0)
    emit(sys.argv[1], sys.argv[2])
